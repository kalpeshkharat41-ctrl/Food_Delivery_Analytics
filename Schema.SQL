-- Create main analytics table
CREATE TABLE food_delivery_analytics (
    order_id VARCHAR(36) PRIMARY KEY,
    city_tier INTEGER,
    customer_age INTEGER,
    customer_loyalty_score NUMERIC(12,8),
    order_hour INTEGER,
    order_day_of_week INTEGER,
    order_month INTEGER,
    delivery_distance_km NUMERIC(12,8),
    preparation_time_minutes INTEGER,
    delivery_time_minutes INTEGER,
    estimated_delivery_time INTEGER,
    traffic_level_score NUMERIC(4,2),
    weather_severity_score NUMERIC(4,2),
    restaurant_rating NUMERIC(3,1),
    delivery_partner_rating NUMERIC(3,1),
    customer_rating NUMERIC(3,1),
    order_value NUMERIC(12,8),
    delivery_fee NUMERIC(12,8),
    discount_amount NUMERIC(12,8),
    tip_amount NUMERIC(12,8),
    final_amount_paid NUMERIC(12,8),
    number_of_items INTEGER,
    cancellation_flag BOOLEAN,
    delayed_delivery_flag BOOLEAN,
    refund_flag BOOLEAN,
    promo_code_used BOOLEAN,
    premium_customer_flag BOOLEAN,
    festival_or_weekend_flag BOOLEAN,
    delivery_partner_experience_years INTEGER,
    delivery_efficiency_score NUMERIC(12,8)
);